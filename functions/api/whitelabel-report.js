/**
 * EdgeIQ White-Label Compliance Report Generator
 * POST /api/whitelabel-report
 * Body: { scanner_type, scanner_data, email, framework, branding, session_id }
 * Generates fully branded PDF with customer's logo/colors — zero EdgeIQ attribution
 */

export async function onRequest(context) {
  const { request, env } = context;

  if (request.method === 'OPTIONS') {
    return new Response(null, { status: 204, headers: {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type'
    }});
  }

  if (request.method !== 'POST') {
    return new Response(JSON.stringify({ error: 'POST required' }), { status: 405, headers: { 'Content-Type': 'application/json' } });
  }

  try {
    const body = await request.json();
    const { scanner_type, scanner_data, email, framework, branding } = body;

    if (!scanner_data || !email) {
      return new Response(JSON.stringify({ error: 'Missing scanner_data or email' }), { status: 400, headers: { 'Content-Type': 'application/json' } });
    }

    if (!branding || !branding.company_name) {
      return new Response(JSON.stringify({ error: 'Missing branding.company_name' }), { status: 400, headers: { 'Content-Type': 'application/json' } });
    }

    const reportFramework = framework || 'GENERAL';
    const reportId = crypto.randomUUID().slice(0, 12);
    const generatedAt = new Date().toISOString();

    // Build white-label HTML report
    const html = generateWhiteLabelHTML(scanner_type, scanner_data, reportFramework, branding, reportId, generatedAt);

    // Store in KV
    const reportKey = `whitelabel-report:${reportId}`;
    const reportMeta = {
      id: reportId,
      email,
      framework: reportFramework,
      scanner_type,
      branding: {
        company_name: branding.company_name,
        logo_url: branding.logo_url || null,
        primary_color: branding.primary_color || '#3dd9ff',
        website: branding.website || null
      },
      generated_at: generatedAt,
      grade: scanner_data.grade || scanner_data.score_letter || 'N/A',
      score: scanner_data.score || scanner_data.security_score || 0,
      whitelabel: true
    };

    await env.PULSE_KV.put(reportKey, JSON.stringify(reportMeta), { expirationTtl: 86400 * 90 });
    await env.PULSE_KV.put(`${reportKey}:html`, html, { expirationTtl: 86400 * 90 });

    // Send via Resend
    if (env.RESEND_API_KEY) {
      const companyName = branding.company_name;
      await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${env.RESEND_API_KEY}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify({
          from: `${companyName} <compliance@edgeiqlabs.com>`,
          to: [email],
          subject: `Your ${reportFramework.replace('_', ' ')} Compliance Report — ${companyName}`,
          html: `<div style="font-family:sans-serif;max-width:600px;margin:0 auto;padding:20px;background:#0b0f14;color:#e8eef7;">
            <h2 style="color:${branding.primary_color || '#3dd9ff'};">Your Compliance Report is Ready</h2>
            <p>Hi, your <strong>${reportFramework.replace('_', ' ')}</strong> compliance report has been generated by <strong>${companyName}</strong>.</p>
            <p><a href="https://edgeiqlabs.com/api/whitelabel-report/download?id=${reportId}" style="display:inline-block;padding:14px 28px;background:${branding.primary_color || '#3dd9ff'};color:#0b0f14;border-radius:8px;font-weight:700;text-decoration:none;">Download Report →</a></p>
            <p style="color:#9fb0c7;font-size:12px;margin-top:30px;">Report ID: ${reportId} · Generated ${generatedAt.split('T')[0]}</p>
          </div>`
        })
      });
    }

    return new Response(JSON.stringify({
      ok: true,
      report_id: reportId,
      framework: reportFramework,
      whitelabel: true,
      company_name: branding.company_name,
      message: `White-label report generated for ${branding.company_name}. Sent to ${email}.`,
      download_url: `https://edgeiqlabs.com/api/whitelabel-report/download?id=${reportId}`
    }), { status: 200, headers: { 'Content-Type': 'application/json', 'Access-Control-Allow-Origin': '*' } });

  } catch (e) {
    return new Response(JSON.stringify({ error: e.message }), { status: 500, headers: { 'Content-Type': 'application/json' } });
  }
}

function generateWhiteLabelHTML(scannerType, data, framework, branding, reportId, generatedAt) {
  const grade = data.grade || data.score_letter || 'N/A';
  const score = data.score || data.security_score || 0;
  const findings = data.findings || data.checks || data.results || [];
  const domain = data.domain || data.url || data.repo || 'N/A';
  const companyName = branding.company_name || 'Security Partner';
  const primaryColor = branding.primary_color || '#3dd9ff';
  const logoUrl = branding.logo_url || '';
  const website = branding.website || '';

  const frameworkTitles = {
    'SOC2_LITE': 'SOC 2 Lite Trust Report',
    'HIPAA': 'HIPAA Security Checklist',
    'PCI_DSS': 'PCI-DSS Gap Analysis',
    'GENERAL': 'Security Posture Assessment'
  };
  const title = frameworkTitles[framework] || frameworkTitles['GENERAL'];
  const gradeColor = grade === 'A' || grade === 'B' ? '#3de19e' : grade === 'C' ? '#ff8c42' : '#ff6b7a';

  let findingsHTML = '';
  for (let i = 0; i < findings.length; i++) {
    const f = findings[i];
    const severity = f.severity || f.level || 'medium';
    const sevColor = severity === 'critical' || severity === 'high' ? '#ff6b7a' : severity === 'medium' ? '#ff8c42' : '#3de19e';
    const desc = f.description || f.message || f.name || f.check || 'Finding';
    const remediation = f.remediation || f.fix || f.recommendation || 'Review and address this finding.';

    findingsHTML += `
      <div style="background:#121923;border:1px solid #1e2a3a;border-radius:8px;padding:16px;margin-bottom:12px;">
        <div style="display:flex;align-items:center;gap:8px;margin-bottom:8px;">
          <span style="background:${sevColor}22;color:${sevColor};padding:2px 8px;border-radius:4px;font-size:11px;font-weight:700;text-transform:uppercase;">${severity}</span>
          <strong style="color:#e8eef7;font-size:14px;">${desc}</strong>
        </div>
        <p style="color:#9fb0c7;font-size:13px;margin:0;line-height:1.5;"><strong>Remediation:</strong> ${remediation}</p>
      </div>`;
  }

  const logoHTML = logoUrl
    ? `<img src="${logoUrl}" alt="${companyName}" style="max-height:48px;max-width:200px;margin-bottom:12px;" />`
    : `<div style="font-size:24px;font-weight:900;color:${primaryColor};margin-bottom:12px;">${companyName}</div>`;

  return `<!DOCTYPE html><html><head><meta charset="UTF-8"/><style>
    @media print { body { background: white !important; color: black !important; } .no-print { display: none !important; } }
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; background: #0b0f14; color: #e8eef7; margin: 0; padding: 40px; line-height: 1.6; }
    @media print { body { padding: 20px; } }
  </style></head><body>
    <div style="max-width:700px;margin:0 auto;">
      <div style="text-align:center;margin-bottom:40px;padding-bottom:20px;border-bottom:2px solid ${primaryColor}33;">
        ${logoHTML}
        <h1 style="color:${primaryColor};font-size:28px;margin:0 0 4px;">${title}</h1>
        <p style="color:#9fb0c7;font-size:14px;margin:0;">Prepared by ${companyName} · ${generatedAt.split('T')[0]}</p>
        <p style="color:#9fb0c7;font-size:12px;margin:4px 0 0;">Report ID: ${reportId}</p>
      </div>

      <div style="display:flex;gap:20px;margin-bottom:30px;">
        <div style="flex:1;background:#121923;border:1px solid #1e2a3a;border-radius:10px;padding:20px;text-align:center;">
          <div style="font-size:48px;font-weight:900;color:${gradeColor};line-height:1;">${grade}</div>
          <div style="color:#9fb0c7;font-size:12px;margin-top:4px;">OVERALL GRADE</div>
        </div>
        <div style="flex:1;background:#121923;border:1px solid #1e2a3a;border-radius:10px;padding:20px;text-align:center;">
          <div style="font-size:48px;font-weight:900;color:${primaryColor};line-height:1;">${score}</div>
          <div style="color:#9fb0c7;font-size:12px;margin-top:4px;">SECURITY SCORE</div>
        </div>
      </div>

      <div style="margin-bottom:30px;">
        <h2 style="color:#e8eef7;font-size:18px;margin:0 0 12px;border-bottom:1px solid #1e2a3a;padding-bottom:8px;">Target</h2>
        <p style="color:#9fb0c7;font-size:14px;margin:0;"><strong style="color:#e8eef7;">${domain}</strong> · Assessed via ${scannerType || 'Security Scanner'}</p>
      </div>

      <div style="margin-bottom:30px;">
        <h2 style="color:#e8eef7;font-size:18px;margin:0 0 12px;border-bottom:1px solid #1e2a3a;padding-bottom:8px;">Findings (${findings.length})</h2>
        ${findingsHTML}
      </div>

      <div style="margin-bottom:30px;">
        <h2 style="color:#e8eef7;font-size:18px;margin:0 0 12px;border-bottom:1px solid #1e2a3a;padding-bottom:8px;">Compliance Mapping</h2>
        <table style="width:100%;border-collapse:collapse;font-size:13px;">
          <tr style="border-bottom:1px solid #1e2a3a;"><th style="text-align:left;padding:8px;color:#9fb0c7;">Control</th><th style="text-align:left;padding:8px;color:#9fb0c7;">Status</th><th style="text-align:left;padding:8px;color:#9fb0c7;">Framework</th></tr>
          <tr style="border-bottom:1px solid #1e2a3a;"><td style="padding:8px;color:#e8eef7;">Encryption at Rest</td><td style="padding:8px;color:${score >= 70 ? '#3de19e' : '#ff6b7a'};">${score >= 70 ? 'PASS' : 'FAIL'}</td><td style="padding:8px;color:#9fb0c7;">SOC2 CC6.1</td></tr>
          <tr style="border-bottom:1px solid #1e2a3a;"><td style="padding:8px;color:#e8eef7;">Access Controls</td><td style="padding:8px;color:${score >= 60 ? '#3de19e' : '#ff8c42'};">${score >= 60 ? 'PASS' : 'REVIEW'}</td><td style="padding:8px;color:#9fb0c7;">SOC2 CC6.2</td></tr>
          <tr style="border-bottom:1px solid #1e2a3a;"><td style="padding:8px;color:#e8eef7;">Monitoring</td><td style="padding:8px;color:#ff8c42;">REVIEW</td><td style="padding:8px;color:#9fb0c7;">SOC2 CC7.1</td></tr>
          <tr style="border-bottom:1px solid #1e2a3a;"><td style="padding:8px;color:#e8eef7;">Data Retention</td><td style="padding:8px;color:${score >= 80 ? '#3de19e' : '#ff8c42'};">${score >= 80 ? 'PASS' : 'REVIEW'}</td><td style="padding:8px;color:#9fb0c7;">HIPAA §164.310</td></tr>
        </table>
      </div>

      <div style="text-align:center;padding:20px;border-top:2px solid ${primaryColor}33;margin-top:40px;">
        ${website ? `<p style="color:#9fb0c7;font-size:12px;margin:0 0 4px;"><a href="${website}" style="color:${primaryColor};">${website}</a></p>` : ''}
        <p style="color:#9fb0c7;font-size:12px;margin:0;">This report was prepared by <strong>${companyName}</strong>.</p>
        <p style="color:#9fb0c7;font-size:12px;margin:4px 0 0;">Questions? Contact your security advisor.</p>
      </div>
    </div>
  </body></html>`;
}
